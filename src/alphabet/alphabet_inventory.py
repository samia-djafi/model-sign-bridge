def get_alphabet_count() -> int:
    """Return total number of letters and auxiliary signs in the alphabet."""
    return len(ALGERIAN_ALPHABET)


def get_alphabet_letter(char_or_id: str) -> Dict[str, Any]:
    """Retrieve metadata for a specific letter."""
    if char_or_id in ALGERIAN_ALPHABET:
        return ALGERIAN_ALPHABET[char_or_id]
    for meta in ALGERIAN_ALPHABET.values():
        if meta["letter_id"] == char_or_id:
            return meta
    return {}
